"""Shared venue-clock calibration for Kalshi timestamp domains.

PROBLEM (2026-10-31 rejection audit): the WS auth handshake measures the
Kalshi server-vs-local skew (``Date`` header) but kept it as a function
local, so every downstream ``local_wall - venue_ts`` staleness comparison
ran uncompensated.  On this host (server - local ~ -3.02s; local clock
runs fast) venue timestamps appeared ~3s older than reality:

* ``ws.py`` superseded ordered orderbook deltas once *apparent* age
  crossed ``KALSHI_BOOK_MAX_EVENT_AGE_MS - margin`` (~3750ms raw, i.e.
  ~730ms of true age), manufacturing sequence gaps and ~780 book
  re-invalidations.
* ``market_state._book_event_timing`` fired ``BOOK_EVENT_TOO_OLD`` at
  ~980ms of true event age.

This module is the single clock-domain helper consumed by both sides.

Conventions
-----------
``server_minus_local_seconds`` is defined as ``server_time - local_time``
(the same sign the WS auth code computes).  A *corrected* venue age is::

    corrected_age = (local_wall + server_minus_local_seconds) - venue_ts

so with s = -3.02s a 3958ms raw age corrects to ~938ms.  Both signs are
handled symmetrically; tests cover +/-.

Transport integrity vs freshness are deliberately separate concerns:
this helper NEVER decides to drop a required ordered delta.  It only
classifies the *age evidence*.  Shed policy (``decide_delta_shed``) is an
overload-shed decision and falls back to monotonic queue residence when
venue age cannot be established.

Unknown/expired offset
----------------------
When no usable calibration exists the result is explicitly
``unverified_*`` — NOT zero, NOT fresh.  Callers keep checking sequence
continuity and monotonic residence, and any consumer needing verified
freshness can see the status field instead of a fabricated number.

Host clock correction
---------------------
The measurement anchors local wall to local monotonic at capture time.
A stepped host clock (``w32tm /resync``, NTP step, manual set) shifts
``time.time()`` while ``time.monotonic()`` is unaffected; divergence
beyond ``step_tolerance`` invalidates the stored offset (status
``unverified_host_clock_step``) until the next reconnect re-measures.

Negative corrected ages
----------------------
A materially negative corrected age (beyond ``neg_age_tolerance_ms``)
means the calibration or timestamp semantics are wrong — it is reported
as ``anomaly_negative_age`` and NOT clamped to zero.

Scope
-----
Applies to timestamps generated by the Kalshi orderbook channel that
shares the calibrated ``external-api.kalshi.com`` clock domain.  Do NOT
reuse this offset for CF Benchmarks RTI/spot or third-party timestamps —
different clock domains need their own calibration.
"""

from __future__ import annotations

import math
import os
import threading
import time
from dataclasses import dataclass
from typing import Any, Dict, Optional

from utils.logger import get_logger

logger = get_logger("merid.event_venues.kalshi.venue_clock")


# ── freshness_status values ─────────────────────────────────────────────────
STATUS_MEASURED = "measured"                          # corrected age is valid
STATUS_NO_VENUE_TS = "no_venue_ts"                    # frame carries no usable ts
STATUS_UNVERIFIED_NO_OFFSET = "unverified_no_offset"  # never measured
STATUS_UNVERIFIED_EXPIRED = "unverified_offset_expired"
STATUS_UNVERIFIED_CLOCK_STEP = "unverified_host_clock_step"
STATUS_ANOMALY_NEGATIVE_AGE = "anomaly_negative_age"
STATUS_ANOMALY_TS = "anomalous_venue_ts"              # unparsable / non-finite

UNVERIFIED_STATUSES = frozenset(
    {
        STATUS_NO_VENUE_TS,
        STATUS_UNVERIFIED_NO_OFFSET,
        STATUS_UNVERIFIED_EXPIRED,
        STATUS_UNVERIFIED_CLOCK_STEP,
    }
)


# ── shed-decision reasons ───────────────────────────────────────────────────
SHED_RESIDENCE = "queue_residence"
SHED_VENUE_AGE = "corrected_venue_age"
SHED_FORWARD = "forward"                                # nothing stale
SHED_FORWARD_UNVERIFIED = "forward_unverified"          # venue age unknowable
SHED_FORWARD_ANOMALY = "forward_anomaly"                # calibration/ts broken
SHED_FORWARD_IMPLAUSIBLE = "forward_implausible_age"    # absurd age, don't trust


def _env_float(name: str, default: float) -> float:
    try:
        return float(os.environ.get(name, default))
    except (TypeError, ValueError):
        return default


def parse_venue_ts_ms(value: Any) -> Optional[float]:
    """Normalize a Kalshi venue timestamp to epoch milliseconds.

    Accepts ISO-8601 strings (``...Z``), epoch seconds, or epoch ms.
    Returns ``None`` when the value is absent or cannot be interpreted.
    """
    if value is None:
        return None
    try:
        if isinstance(value, str):
            from datetime import datetime

            return (
                datetime.fromisoformat(value.replace("Z", "+00:00")).timestamp()
                * 1000.0
            )
        num = float(value)
        if not (num == num) or num in (float("inf"), float("-inf")):
            return None
        return num if num > 1e12 else num * 1000.0
    except Exception:
        return None


@dataclass(frozen=True)
class ClockOffsetMeasurement:
    """One calibrated server-minus-local offset sample."""

    server_minus_local_seconds: float
    measured_at_wall: float        # time.time() at capture
    measured_at_monotonic: float   # time.monotonic() at capture
    source: str                    # e.g. "kalshi_ws_auth_date_header"
    precision_seconds: float       # honest bound: Date granularity + rtt/2
    rtt_seconds: Optional[float]   # request round-trip, None if unmeasured


@dataclass(frozen=True)
class OffsetState:
    """Validity of the stored calibration at evaluation time."""

    offset_seconds: Optional[float]
    measurement_age_s: Optional[float]
    source: Optional[str]
    precision_seconds: Optional[float]
    rtt_seconds: Optional[float]
    valid: bool
    invalid_reason: Optional[str]  # no_measurement | expired | host_clock_step


@dataclass(frozen=True)
class VenueTimingResult:
    """Clock-domain timing for one venue-timestamped frame."""

    receipt_monotonic_ns: Optional[float]
    receipt_wall_ms: Optional[float]
    queue_residence_ms: Optional[float]        # monotonic-domain, skew-free
    local_pipeline_age_ms: Optional[float]     # now_wall - receipt_wall (local-local)
    raw_venue_age_ms: Optional[float]          # local_wall - venue_ts (uncorrected)
    corrected_venue_age_ms: Optional[float]    # (local_wall + offset) - venue_ts
    offset_seconds: Optional[float]            # server_minus_local
    offset_measurement_age_s: Optional[float]
    offset_source: Optional[str]
    offset_valid: bool
    freshness_status: str


@dataclass(frozen=True)
class ShedDecision:
    """Overload-shed verdict for one queued orderbook delta."""

    drop: bool
    reason: str
    timing: VenueTimingResult


class VenueClockCalibration:
    """Process-wide offset store for one venue clock domain."""

    def __init__(
        self,
        venue: str = "kalshi",
        *,
        max_offset_age_s: Optional[float] = None,
        step_tolerance_s: Optional[float] = None,
        neg_age_tolerance_ms: Optional[float] = None,
    ) -> None:
        self.venue = venue
        self._max_offset_age_s = (
            max_offset_age_s
            if max_offset_age_s is not None
            else _env_float("MERID_VENUE_CLOCK_MAX_OFFSET_AGE_S", 1800.0)
        )
        self._step_tolerance_s = (
            step_tolerance_s
            if step_tolerance_s is not None
            else _env_float("MERID_VENUE_CLOCK_STEP_TOLERANCE_S", 0.5)
        )
        self._neg_age_tolerance_ms = (
            neg_age_tolerance_ms
            if neg_age_tolerance_ms is not None
            else _env_float("MERID_VENUE_CLOCK_NEG_AGE_TOLERANCE_MS", 1500.0)
        )
        self._lock = threading.Lock()
        self._m: Optional[ClockOffsetMeasurement] = None

    # ── calibration lifecycle ───────────────────────────────────────────
    def record_measurement(
        self,
        server_minus_local_seconds: float,
        *,
        source: str,
        precision_seconds: float,
        rtt_seconds: Optional[float] = None,
        measured_at_wall: Optional[float] = None,
        measured_at_monotonic: Optional[float] = None,
    ) -> ClockOffsetMeasurement:
        """Store a fresh offset sample (called once per WS auth)."""
        m = ClockOffsetMeasurement(
            server_minus_local_seconds=float(server_minus_local_seconds),
            measured_at_wall=(
                time.time() if measured_at_wall is None else measured_at_wall
            ),
            measured_at_monotonic=(
                time.monotonic()
                if measured_at_monotonic is None
                else measured_at_monotonic
            ),
            source=source,
            precision_seconds=float(precision_seconds),
            rtt_seconds=rtt_seconds,
        )
        with self._lock:
            self._m = m
        logger.info(
            "[VENUE-CLOCK] %s offset=%+.3fs src=%s precision=+/-%.2fs rtt=%s",
            self.venue,
            m.server_minus_local_seconds,
            m.source,
            m.precision_seconds,
            f"{m.rtt_seconds:.3f}s" if m.rtt_seconds is not None else "n/a",
        )
        return m

    def invalidate(self, reason: str) -> None:
        with self._lock:
            self._m = None
        logger.warning("[VENUE-CLOCK] %s calibration cleared: %s", self.venue, reason)

    def record_measurement_if_newer(self, measurement: ClockOffsetMeasurement) -> bool:
        """Do not let a delayed refresh overwrite a newer authentication sample."""
        with self._lock:
            if self._m is not None and (
                self._m.measured_at_monotonic >= measurement.measured_at_monotonic
            ):
                return False
            self._m = measurement
        logger.info(
            "[VENUE-CLOCK] %s refreshed offset=%+.3fs src=%s precision=+/-%.2fs rtt=%s",
            self.venue, measurement.server_minus_local_seconds, measurement.source,
            measurement.precision_seconds, measurement.rtt_seconds,
        )
        return True

    def refresh_after_seconds(self) -> float:
        """Refresh comfortably before expiry, without increasing its threshold."""
        if not math.isfinite(self._max_offset_age_s) or self._max_offset_age_s <= 0:
            return 1.0
        return max(1.0, min(600.0, self._max_offset_age_s / 2.0))

    def offset_state(
        self,
        *,
        now_wall: Optional[float] = None,
        now_monotonic: Optional[float] = None,
    ) -> OffsetState:
        """Current calibration validity, checked against monotonic time.

        A stepped host clock is detected by comparing ``time.time()`` to the
        wall time predicted from the monotonic anchor captured with the
        measurement.
        """
        now_wall = time.time() if now_wall is None else now_wall
        now_monotonic = (
            time.monotonic() if now_monotonic is None else now_monotonic
        )
        with self._lock:
            m = self._m
        if m is None:
            return OffsetState(
                offset_seconds=None,
                measurement_age_s=None,
                source=None,
                precision_seconds=None,
                rtt_seconds=None,
                valid=False,
                invalid_reason="no_measurement",
            )
        age_s = now_monotonic - m.measured_at_monotonic
        if age_s > self._max_offset_age_s:
            return OffsetState(
                offset_seconds=m.server_minus_local_seconds,
                measurement_age_s=age_s,
                source=m.source,
                precision_seconds=m.precision_seconds,
                rtt_seconds=m.rtt_seconds,
                valid=False,
                invalid_reason="expired",
            )
        expected_wall = m.measured_at_wall + age_s
        if abs(now_wall - expected_wall) > self._step_tolerance_s:
            # Host wall clock stepped since calibration (resync / manual set /
            # NTP step).  The stored offset is wrong until re-measured.
            return OffsetState(
                offset_seconds=m.server_minus_local_seconds,
                measurement_age_s=age_s,
                source=m.source,
                precision_seconds=m.precision_seconds,
                rtt_seconds=m.rtt_seconds,
                valid=False,
                invalid_reason="host_clock_step",
            )
        return OffsetState(
            offset_seconds=m.server_minus_local_seconds,
            measurement_age_s=age_s,
            source=m.source,
            precision_seconds=m.precision_seconds,
            rtt_seconds=m.rtt_seconds,
            valid=True,
            invalid_reason=None,
        )

    # ── per-frame evaluation ────────────────────────────────────────────
    def evaluate_venue_ts(
        self,
        venue_ts_ms: Optional[float],
        *,
        now_wall_ms: Optional[float] = None,
        now_monotonic_ns: Optional[int] = None,
        receipt_monotonic_ns: Optional[float] = None,
        receipt_wall_ms: Optional[float] = None,
        queue_residence_ms: Optional[float] = None,
    ) -> VenueTimingResult:
        """Build the clock-domain timing result for one frame."""
        if now_wall_ms is None:
            now_wall_ms = time.time() * 1000.0
        if now_monotonic_ns is None:
            now_monotonic_ns = time.monotonic_ns()

        if queue_residence_ms is None and receipt_monotonic_ns is not None:
            try:
                queue_residence_ms = (
                    float(now_monotonic_ns) - float(receipt_monotonic_ns)
                ) / 1e6
            except Exception:
                queue_residence_ms = None

        local_pipeline_age_ms: Optional[float] = None
        if receipt_wall_ms is not None:
            try:
                # Local-wall vs local-wall: skew-free lower bound on
                # in-process delay.  Cannot see venue->socket upstream lag.
                local_pipeline_age_ms = now_wall_ms - float(receipt_wall_ms)
            except Exception:
                local_pipeline_age_ms = None

        raw_venue_age_ms: Optional[float] = None
        if venue_ts_ms is not None:
            try:
                if 0 < float(venue_ts_ms):
                    raw_venue_age_ms = now_wall_ms - float(venue_ts_ms)
            except Exception:
                raw_venue_age_ms = None

        if venue_ts_ms is None:
            return VenueTimingResult(
                receipt_monotonic_ns=receipt_monotonic_ns,
                receipt_wall_ms=receipt_wall_ms,
                queue_residence_ms=queue_residence_ms,
                local_pipeline_age_ms=local_pipeline_age_ms,
                raw_venue_age_ms=raw_venue_age_ms,
                corrected_venue_age_ms=None,
                offset_seconds=None,
                offset_measurement_age_s=None,
                offset_source=None,
                offset_valid=False,
                freshness_status=STATUS_NO_VENUE_TS,
            )
        if raw_venue_age_ms is None:
            return VenueTimingResult(
                receipt_monotonic_ns=receipt_monotonic_ns,
                receipt_wall_ms=receipt_wall_ms,
                queue_residence_ms=queue_residence_ms,
                local_pipeline_age_ms=local_pipeline_age_ms,
                raw_venue_age_ms=None,
                corrected_venue_age_ms=None,
                offset_seconds=None,
                offset_measurement_age_s=None,
                offset_source=None,
                offset_valid=False,
                freshness_status=STATUS_ANOMALY_TS,
            )

        off = self.offset_state(
            now_wall=now_wall_ms / 1000.0,
            now_monotonic=now_monotonic_ns / 1e9,
        )
        if not off.valid or off.offset_seconds is None:
            status = {
                "no_measurement": STATUS_UNVERIFIED_NO_OFFSET,
                "expired": STATUS_UNVERIFIED_EXPIRED,
                "host_clock_step": STATUS_UNVERIFIED_CLOCK_STEP,
            }.get(off.invalid_reason or "", STATUS_UNVERIFIED_NO_OFFSET)
            return VenueTimingResult(
                receipt_monotonic_ns=receipt_monotonic_ns,
                receipt_wall_ms=receipt_wall_ms,
                queue_residence_ms=queue_residence_ms,
                local_pipeline_age_ms=local_pipeline_age_ms,
                raw_venue_age_ms=raw_venue_age_ms,
                corrected_venue_age_ms=None,
                offset_seconds=off.offset_seconds,
                offset_measurement_age_s=off.measurement_age_s,
                offset_source=off.source,
                offset_valid=False,
                freshness_status=status,
            )

        corrected = (now_wall_ms + off.offset_seconds * 1000.0) - float(
            venue_ts_ms
        )
        if corrected < -self._neg_age_tolerance_ms:
            # Materially future venue ts even after correction: calibration or
            # timestamp semantics are broken.  Report, do not clamp.
            status = STATUS_ANOMALY_NEGATIVE_AGE
        else:
            status = STATUS_MEASURED
        return VenueTimingResult(
            receipt_monotonic_ns=receipt_monotonic_ns,
            receipt_wall_ms=receipt_wall_ms,
            queue_residence_ms=queue_residence_ms,
            local_pipeline_age_ms=local_pipeline_age_ms,
            raw_venue_age_ms=raw_venue_age_ms,
            corrected_venue_age_ms=corrected,
            offset_seconds=off.offset_seconds,
            offset_measurement_age_s=off.measurement_age_s,
            offset_source=off.source,
            offset_valid=True,
            freshness_status=status,
        )


def decide_delta_shed(
    *,
    queue_residence_ms: Optional[float],
    residence_bound_ms: float,
    timing: VenueTimingResult,
    venue_age_bound_ms: float,
    implausible_age_multiplier: float = 4.0,
) -> ShedDecision:
    """Overload-shed verdict for one queued orderbook delta.

    This decides *only* whether a queued frame is too costly to replay.
    It is not a freshness verdict and never alters sequence accounting —
    a dropped frame must still invalidate the affected reconstruction via
    the sequence/recovery layer.

    The monotonic residence bound is authoritative overload protection:
    once a frame out-waits it, shedding fires regardless of venue
    freshness (the loop is provably behind; a shed frame still flows
    through attributed invalidation + snapshot recovery, which is safe).
    Venue-age shedding adds a second, *measured* bound for frames whose
    corrected event age can no longer yield tradable evidence.  An
    unverifiable or anomalous venue age never sheds on its own — dropping
    on a broken measurement manufactures invalidations.
    """
    if (
        queue_residence_ms is not None
        and queue_residence_ms > residence_bound_ms
    ):
        return ShedDecision(True, SHED_RESIDENCE, timing)
    st = timing.freshness_status
    if st == STATUS_MEASURED and timing.corrected_venue_age_ms is not None:
        age = timing.corrected_venue_age_ms
        if age >= venue_age_bound_ms:
            if age < venue_age_bound_ms * implausible_age_multiplier:
                # Verified-stale: cannot yield tradable evidence downstream.
                return ShedDecision(True, SHED_VENUE_AGE, timing)
            # Absurd corrected age implies broken calibration/ts semantics —
            # do not manufacture a gap on an untrusted measurement.
            return ShedDecision(False, SHED_FORWARD_IMPLAUSIBLE, timing)
        return ShedDecision(False, SHED_FORWARD, timing)
    if st in UNVERIFIED_STATUSES:
        # Cannot establish venue age: do not shed, and do NOT silently treat
        # the frame as fresh — consumers see timing.freshness_status.
        return ShedDecision(False, SHED_FORWARD_UNVERIFIED, timing)
    # Anomalous calibration/ts: keep the frame; dropping on a broken
    # measurement manufactures invalidations.
    return ShedDecision(False, SHED_FORWARD_ANOMALY, timing)


# ── process-wide registry ─────────────────────────────────────────────────
_CLOCKS: Dict[str, VenueClockCalibration] = {}
_CLOCKS_LOCK = threading.Lock()


def get_venue_clock(venue: str = "kalshi") -> VenueClockCalibration:
    """Return the shared calibration object for a venue clock domain."""
    with _CLOCKS_LOCK:
        clk = _CLOCKS.get(venue)
        if clk is None:
            clk = _CLOCKS[venue] = VenueClockCalibration(venue)
        return clk
