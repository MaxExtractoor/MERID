"""
Prometheus Metrics Schema for 15m Pipeline Observability

Defines metrics that map directly to PipelineObservability fields for
Grafana dashboards and alerting.

Metric Naming Convention:
- merid_pipeline_<metric_name> for pipeline-level metrics
- merid_feature_<metric_name> for feature namespace metrics
- merid_risk_<metric_name> for risk check metrics
- merid_execution_<metric_name> for execution metrics

Labels:
- asset: BTC, ETH, SOL, XRP, DOGE
- pipeline_id: btc_15m_pipeline, eth_15m_pipeline, etc.
- namespace: ts_15m, sentiment, regime, etc.
- agent_name: Specific agent name
- decision_side: yes, no, none
- risk_check_name: max_size, asset_exposure, etc.
"""

