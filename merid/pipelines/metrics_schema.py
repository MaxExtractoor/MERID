class PipelineMetricsExporter:
    """
    Exports pipeline observability metrics to Prometheus.
    
    Maps PipelineObservability and DecisionTrace fields to Prometheus metrics.
    """
    
    def __init__(self):
        self.pipeline_success_counts: Dict[str, Dict[str, int]] = {}
        self.agent_success_counts: Dict[str, Dict[str, int]] = {}
    
    def export_trace(self, trace: Any) -> None:
        """Export a DecisionTrace to Prometheus metrics."""
        asset = trace.asset
        pipeline_id = trace.pipeline_id
        
        # Update cycle counts
        self.pipeline_success_counts.setdefault(asset, {}).setdefault(pipeline_id, {})
        self.pipeline_success_counts[asset][pipeline_id]['cycles'] = \
            self.pipeline_success_counts[asset][pipeline_id].get('cycles', 0) + 1
        
        # Export timing metrics
        pipeline_feature_build_duration_seconds.labels(
            asset=asset, pipeline_id=pipeline_id
        ).observe(trace.feature_build_ms / 1000)
        
        pipeline_decision_duration_seconds.labels(
            asset=asset, pipeline_id=pipeline_id
        ).observe(trace.decision_ms / 1000)
        
        pipeline_risk_check_duration_seconds.labels(
            asset=asset, pipeline_id=pipeline_id
        ).observe(trace.risk_check_ms / 1000)
        
        pipeline_execution_duration_seconds.labels(
            asset=asset, pipeline_id=pipeline_id
        ).observe(trace.execution_ms / 1000)
        
        pipeline_total_duration_seconds.labels(
            asset=asset, pipeline_id=pipeline_id
        ).observe(trace.total_ms / 1000)
        
        # Export feature namespace metrics
        for namespace, summary in trace.feature_summaries.items():
            feature_namespace_feature_count.labels(
                asset=asset, pipeline_id=pipeline_id, namespace=namespace
            ).set(summary.feature_count)
            
            feature_namespace_mean_value.labels(
                asset=asset, pipeline_id=pipeline_id, namespace=namespace
            ).set(summary.mean_value)
            
            feature_namespace_std_value.labels(
                asset=asset, pipeline_id=pipeline_id, namespace=namespace
            ).set(summary.std_value)
            
            feature_namespace_missing_count.labels(
                asset=asset, pipeline_id=pipeline_id, namespace=namespace
            ).set(summary.missing_count)
            
            # Calculate sparsity
            total = summary.feature_count + summary.missing_count
            sparsity = summary.missing_count / total if total > 0 else 0
            feature_namespace_sparsity.labels(
                asset=asset, pipeline_id=pipeline_id, namespace=namespace
            ).set(sparsity)
        
        # Export decision metrics
        if trace.decision:
            pipeline_decisions_total.labels(
                asset=asset, pipeline_id=pipeline_id, decision_side=trace.decision.side
            ).inc()
            
            pipeline_decisions_confidence.labels(
                asset=asset, pipeline_id=pipeline_id
            ).observe(trace.decision.confidence)
            
            pipeline_decisions_edge_estimate.labels(
                asset=asset, pipeline_id=pipeline_id
            ).observe(trace.decision.edge_estimate)
            
            pipeline_decisions_size_pct.labels(
                asset=asset, pipeline_id=pipeline_id
            ).observe(trace.decision.size_pct)
            
            self.pipeline_success_counts[asset][pipeline_id]['decisions'] = \
                self.pipeline_success_counts[asset][pipeline_id].get('decisions', 0) + 1
        
        # Export risk check metrics
        for risk_check in trace.risk_checks:
            check_name = risk_check['check_name']
            risk_check_total.labels(
                asset=asset, pipeline_id=pipeline_id, check_name=check_name
            ).inc()
            
            if risk_check['passed']:
                risk_check_passed.labels(
                    asset=asset, pipeline_id=pipeline_id, check_name=check_name
                ).inc()
            else:
                risk_check_failed.labels(
                    asset=asset, pipeline_id=pipeline_id, check_name=check_name
                ).inc()
            
            if risk_check.get('adjusted_size_pct'):
                original_size = trace.decision.size_pct if trace.decision else 0
                adjustment = original_size - risk_check['adjusted_size_pct']
                risk_adjustment_amount.labels(
                    asset=asset, pipeline_id=pipeline_id, check_name=check_name
                ).observe(adjustment)
        
        # Export execution metrics
        if trace.execution_success:
            execution_orders_success.labels(
                asset=asset, pipeline_id=pipeline_id
            ).inc()
        else:
            execution_orders_failed.labels(
                asset=asset, pipeline_id=pipeline_id, error_type=trace.execution_error
            ).inc()
        
        # Update success rate
        cycles = self.pipeline_success_counts[asset][pipeline_id].get('cycles', 0)
        decisions = self.pipeline_success_counts[asset][pipeline_id].get('decisions', 0)
        if cycles > 0:
            success_rate = decisions / cycles
            pipeline_success_rate.labels(
                asset=asset, pipeline_id=pipeline_id
            ).set(success_rate)
        
        # Update timestamps
        pipeline_last_cycle_timestamp.labels(
            asset=asset, pipeline_id=pipeline_id
        ).set(trace.timestamp.timestamp())
        
        if trace.decision:
            pipeline_last_decision_timestamp.labels(
                asset=asset, pipeline_id=pipeline_id
            ).set(trace.timestamp.timestamp())
    
    def export_health_metrics(self, observability: Any) -> None:
        """Export health metrics from PipelineObservability."""
        health_summary = observability.get_health_summary()
        
        # Export feature sparsity health
        for namespace, sparsity_data in health_summary.get('feature_sparsity', {}).items():
            avg_sparsity = sparsity_data.get('avg_sparsity', 0)
            # This is already exported per-trace, but we can add aggregated health here
            pass
    
    def export_agent_metrics(
        self,
        asset: str,
        pipeline_id: str,
        agent_name: str,
        namespace: str,
        duration_ms: float,
        success: bool,
    ) -> None:
        """Export feature agent invocation metrics."""
        feature_agent_invocation_duration_seconds.labels(
            asset=asset, pipeline_id=pipeline_id, agent_name=agent_name, namespace=namespace
        ).observe(duration_ms / 1000)
        
        # Update success counts
        key = f"{asset}:{pipeline_id}:{agent_name}"
        self.agent_success_counts.setdefault(key, {})
        self.agent_success_counts[key]['total'] = self.agent_success_counts[key].get('total', 0) + 1
        self.agent_success_counts[key]['success'] = self.agent_success_counts[key].get('success', 0) + (1 if success else 0)
        
        # Update success rate
        total = self.agent_success_counts[key]['total']
        success_rate = self.agent_success_counts[key]['success'] / total if total > 0 else 0
        feature_agent_invocation_success_rate.labels(
            asset=asset, pipeline_id=pipeline_id, agent_name=agent_name, namespace=namespace
        ).set(success_rate)
        
        # Update health status
        feature_agent_healthy.labels(
            asset=asset, pipeline_id=pipeline_id, agent_name=agent_name
        ).set(1 if success_rate > 0.8 else 0)


