@dataclass
class Signal:
    """Trading signal generated by agent."""
    asset: str
    market_id: str
    direction: str  # YES or NO
    contracts: int
    price_cents: int
    edge_pct: float
    timestamp: float


@dataclass
class Candidate:
    """Trade candidate after gate validation."""
    signal: Signal
    gate_decision: dict
    timestamp: float
    
    @property
    def market_id(self):
        """Convenience property to access signal market_id."""
        return self.signal.market_id


@dataclass
class Order:
    """Order placed with Kalshi."""
    order_id: str
    market_id: str
    direction: str
    contracts: int
    price_cents: int
    status: str  # PENDING, OPEN, FILLED, EXPIRED, CANCELLED
    timestamp: float


@dataclass
class Fill:
    """Fill confirmation from Kalshi."""
    order_id: str
    market_id: str
    direction: str
    contracts: int
    price_cents: int
    timestamp: float


@dataclass
class Position:
    """Position after fill."""
    market_id: str
    direction: str
    contracts: int
    entry_price_cents: int
    current_price_cents: Optional[int]
    pnl_cents: float


