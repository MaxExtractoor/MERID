@pytest.fixture
def calculate_pnl():
    """Helper function to calculate PnL."""
    def _calculate(fill, settlement_price_cents, risk_env):
        # Calculate PnL: (settlement - entry) * contracts * direction
        # For YES: (settlement - entry) * contracts
        # For NO: (entry - settlement) * contracts
        if fill.direction == "YES":
            pnl_cents = (settlement_price_cents - fill.price_cents) * fill.contracts
        else:
            pnl_cents = (fill.price_cents - settlement_price_cents) * fill.contracts
        
        # Update risk environment
        risk_env.update_position(
            market_id=fill.market_id,
            contracts=fill.contracts,
            pnl_cents=pnl_cents,
        )
        
        return Position(
            market_id=fill.market_id,
            direction=fill.direction,
            contracts=fill.contracts,
            entry_price_cents=fill.price_cents,
            current_price_cents=settlement_price_cents,
            pnl_cents=pnl_cents,
        )
    return _calculate
